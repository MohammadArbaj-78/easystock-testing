-- Agency contacts: the WhatsApp number of an agency (asked once, on the first
-- "WhatsApp reminder" tap in Low Stock -> Agency), so the next time the chat
-- of that agency opens directly.
-- Run this ONCE in the Supabase SQL editor. Safe to run again.
-- Without this table the app keeps working: it just cannot remember numbers.

create table if not exists agency_contacts (
    contact_id  bigint generated by default as identity primary key,
    store_id    bigint not null references stores (store_id),
    agency_id   bigint not null,
    mobile      text   not null,
    updated_at  timestamptz not null default now(),
    unique (store_id, agency_id)
);

create index if not exists idx_agency_contacts_store
    on agency_contacts (store_id);

-- Row level security ON with the same open policy the other EasyStock
-- tables use (<table>_all_access). The app limits every read / write to the
-- logged-in store. Safe to run again.
alter table agency_contacts enable row level security;
drop policy if exists agency_contacts_all_access on agency_contacts;
create policy agency_contacts_all_access on agency_contacts
    for all to anon, authenticated
    using (true) with check (true);
